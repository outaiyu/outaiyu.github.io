/* ════════════════════════════════════════════════════════════════════════
   Standalone builder — packs the whole game into one .html file.

   Useful when uploading is a chore: NeoCities' file manager is fiddly,
   emailing a build to someone means one attachment, and a single file
   survives being renamed, moved, or dropped on a tablet with no server.

   Everything is inlined: stylesheet, the WebSocket recorder, all six
   scripts, and the vendored Trystero library. The favicon was already a
   data: URI. The result still makes no network requests of its own.

       node build-standalone.js            → ../moneyman-upload/moneyman-standalone.html
       node build-standalone.js out.html   → that path instead

   The multi-file version stays the thing to develop and deploy; this is
   generated, so never edit the output by hand.
   ════════════════════════════════════════════════════════════════════════ */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const OUT = process.argv[2]
  || path.join(ROOT, "..", "moneyman-upload", "moneyman-standalone.html");

const read = f => fs.readFileSync(path.join(ROOT, f), "utf8");

let html = read("index.html");
const packed = [];

/* stylesheet → <style> */
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => {
  packed.push(href);
  return "<style>\n" + read(href) + "\n</style>";
});

/* <script src="x"> → <script>x</script> */
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => {
  packed.push(src);
  return "<script>\n" + read(src) + "\n</script>";
});

/* nothing may still point at a separate file */
const leftovers = [...html.matchAll(/(?:src|href)="([^"]+)"/g)]
  .map(m => m[1])
  .filter(u => !/^(?:https?:|data:|#|mailto:)/.test(u));
if (leftovers.length)
  throw new Error("still references external files: " + leftovers.join(", "));

if (/\.mp3/i.test(html)) throw new Error("an .mp3 reference survived");

const banner = "<!-- MONEYMAN — standalone build. Generated by build-standalone.js; do not edit. -->\n";
fs.writeFileSync(OUT, banner + html);

const kb = (fs.statSync(OUT).size / 1024).toFixed(0);
console.log("packed " + packed.length + " files into " + OUT);
console.log("  " + packed.join(", "));
console.log("  " + kb + " KB, 0 external requests");